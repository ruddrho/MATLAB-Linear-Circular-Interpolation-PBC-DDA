function exportCNCReport(fileName,comparison,params)
%EXPORTCNCREPORT Create an A4 one-page research-style report (base MATLAB).
% Text, ideal path, discrete PBC/DDA paths and metrics are printable to PDF.
    if isempty(comparison) || ~isfield(comparison,'Metrics')
        error('Report:MissingComparison','Run algorithm comparison first.');
    end
    [folder,~,ext]=fileparts(char(fileName));
    if ~strcmpi(ext,'.pdf'),error('Report:Extension','Output must be a PDF.');end
    if ~isempty(folder) && ~isfolder(folder)
        error('Report:Folder','Destination directory does not exist.');
    end
    fig=figure('Visible','off','Color','white', ...
        'Position',[100 100 880 1110], ...
        'PaperUnits','centimeters','PaperType','A4', ...
        'PaperOrientation','portrait', ...
        'PaperPositionMode','auto');
    cleanup=onCleanup(@()close(fig)); %#ok<NASGU>
    annotation(fig,'textbox',[.07 .93 .87 .05], ...
        'String','CNC INTERPOLATION | ANALYSIS REPORT', ...
        'FontSize',21,'FontWeight','bold','Color',[.05 .18 .30], ...
        'EdgeColor','none');
    annotation(fig,'textbox',[.07 .882 .86 .05], ...
        'String',sprintf('Generated: %s  |  PBC and DDA comparison',datestr(now,31)), ...
        'FontSize',10,'EdgeColor','none');
    info=sprintf(['Geometry: %s     Direction: %s\n', ...
        'Start: (%g, %g)   End: (%g, %g)   Center: (%g, %g)'], ...
        char(params.PathType),char(params.Direction), ...
        params.Start(1),params.Start(2),params.End(1),params.End(2), ...
        params.Center(1),params.Center(2));
    annotation(fig,'textbox',[.07 .826 .86 .048], ...
        'String',info,'FontSize',10,'EdgeColor','none');
    ax=axes('Parent',fig,'Position',[.10 .46 .79 .34]);
    hold(ax,'on');grid(ax,'on');axis(ax,'equal');
    p=comparison.PBC;d=comparison.DDA;
    plot(ax,p.ideal(:,1),p.ideal(:,2),'k--','LineWidth',1.4, ...
        'DisplayName','Command path');
    plot(ax,p.points(:,1),p.points(:,2),'-', ...
        'Color',[.88 .28 .42],'LineWidth',1.6, 'DisplayName','PBC');
    plot(ax,d.points(:,1),d.points(:,2),'-', ...
        'Color',[.00 .48 .68],'LineWidth',1.35, 'DisplayName','DDA');
    scatter(ax,p.points(1,1),p.points(1,2),45,[.10 .72 .62],'filled', ...
        'DisplayName','Start S');
    scatter(ax,p.points(end,1),p.points(end,2),45,[.98 .67 .17],'s','filled', ...
        'DisplayName','End E');
    title(ax,'Ideal and discrete toolpath comparison');
    xlabel(ax,'X (grid pulses)');ylabel(ax,'Y (grid pulses)');
    legend(ax,'Location','bestoutside');
    m=comparison.Metrics;
    metricLines=sprintf([ ...
        'METRIC                                PBC                     DDA\n', ...
        'Pulse / clock cycles              %8d                %8d\n', ...
        'Maximum geometric error         %10.4f               %10.4f\n', ...
        'Mean geometric error            %10.4f               %10.4f\n', ...
        'Endpoint error                  %10.4f               %10.4f\n', ...
        'Discrete path length           %10.4f               %10.4f\n', ...
        'CPU evaluation time (ms)       %10.3f               %10.3f'], ...
        m.PulseCycles(1),m.PulseCycles(2),m.MaxDeviation(1),m.MaxDeviation(2), ...
        m.MeanDeviation(1),m.MeanDeviation(2), ...
        m.EndpointError(1),m.EndpointError(2), ...
        m.PathLength(1),m.PathLength(2), ...
        m.CPUTimeMs(1),m.CPUTimeMs(2));
    annotation(fig,'textbox',[.08 .20 .84 .23], ...
        'String',metricLines,'FontName','Courier New','FontSize',10, ...
        'Interpreter','none','EdgeColor',[.7 .76 .8], ...
        'BackgroundColor',[.97 .98 .99]);
    annotation(fig,'textbox',[.08 .075 .84 .10], ...
        'String',['NOTE: Educational integer-grid interpolation, not CNC ', ...
        'machine-control G-code. PBC is one-axis-per-pulse; DDA can pulse ', ...
        'both axes per clock. CPU time is environment-dependent. Circular ', ...
        'geometric error is radial deviation.'], ...
        'FontSize',9,'EdgeColor','none','Color',[.27 .30 .35]);
    print(fig,char(fileName),'-dpdf','-bestfit');
end
